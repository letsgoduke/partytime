import React,{Suspense,lazy} from 'react';
import ReactDOM from 'react-dom/client';
import {BrowserRouter,Routes,Route} from 'react-router-dom';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import App from './App';
import './styles.css';
const Parties=lazy(()=>import('./pages/Parties'));
const Create=lazy(()=>import('./pages/Create'));
const Dashboard=lazy(()=>import('./pages/Dashboard'));
const Profile=lazy(()=>import('./pages/Profile'));
const queryClient=new QueryClient({defaultOptions:{queries:{retry:1,refetchOnWindowFocus:false}}});
ReactDOM.createRoot(document.getElementById('root')!).render(<React.StrictMode><QueryClientProvider client={queryClient}><BrowserRouter><Suspense fallback={<p className="loading">Getting things ready…</p>}><Routes><Route path="/" element={<App/>}/><Route path="/invite/:token" element={<App/>}/><Route path="/manage" element={<App manage/>}/><Route path="/parties" element={<Parties/>}/><Route path="/create" element={<Create/>}/><Route path="/host/:partyId" element={<Dashboard/>}/><Route path="/profile" element={<Profile/>}/></Routes></Suspense></BrowserRouter></QueryClientProvider></React.StrictMode>);
if('serviceWorker' in navigator)void navigator.serviceWorker.register('/sw.js');
